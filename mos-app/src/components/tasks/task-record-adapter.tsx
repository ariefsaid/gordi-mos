export type TaskViewerFieldKey =
  | 'title'
  | 'description'
  | 'dueDate'
  | 'businessUnit'
  | 'pic'
  | 'supervisor'
  | 'projectProcess'
  | 'objective'

export interface TaskTeamView {
  id: string
  label: string
}

export interface TaskRecordAdapterInput {
  detail: TaskDetail
  viewerId: string
  /** #742 AC-061 (delta): the viewer's already-loaded downline person ids — the raw fact
   *  canEdit/canArchive derive "viewer is above the PIC" from. The helper owns that derivation;
   *  this adapter never receives a viewer-global isManager. Empty for an unauthenticated viewer. */
  downlineIds: readonly string[]
  people: readonly PersonOption[]
  businessUnits: readonly BusinessUnitOption[]
  objectives?: readonly ObjectiveRow[]
  workLines?: readonly WorkLineRow[]
  labels?: TaskFieldLabels
  /** Locale-resolved chrome labels for the full record (LocaleParityContract). */
  recordLabels?: Partial<TaskRecordLabels>
  /**
   * Only a real task.team_id lookup may populate this value. Omit or pass null while
   * the current mos.tasks row has no team_id (Issue 8 BU→Team re-home dependency).
   */
  team?: TaskTeamView | null
  /**
   * The generating `mos.process_task_defs.title` for a task materialized by
   * `mos.spawn_process_run` / `mos.resolve_pending_task` (ADR-0051 Step 6, real
   * `task.generated_from_task_def_id`). Omit or pass null for a hand-created (ad hoc)
   * task, or while the label lookup hasn't resolved yet — the "Generated by" chip is
   * conditional (E7 record grammar), never a fabricated placeholder.
   */
  generatedFromLabel?: string | null
  /**
   * Formats an ISO `YYYY-MM-DD` into the record's DISPLAY string. The live TaskSurface passes the
   * SAME `task-formatters.formatDate` family the table row uses (V3 owner-eyes item 2) so a record's
   * Due reads "Wed 8 Jul", never the raw ISO "2026-07-08". Omitted → the raw ISO is shown (keeps the
   * adapter's own unit tests literal). The field's `value` stays the ISO string for the edit control.
   */
  formatDate?: (iso: string) => string
  /** Formats a last-activity ISO timestamp into the meta line's compact age ("5h"); the SAME
   *  formatter family the table row uses. Omitted → the activity-age item is skipped. */
  formatAge?: (iso: string) => string
  onUpdateField: (field: TaskViewerFieldKey, value: string | null) => Promise<void>
  onUpdateStatus: (next: TaskStatus) => Promise<void>
  onArchive: () => Promise<void>
  onUnarchive: () => Promise<void>
  onOpenRelated?: (relation: RecordRelation) => void
}

