function personOptions(people: readonly PersonOption[]): RecordFieldOption[] {
  return people.map((p) => ({ value: p.id, label: p.full_name }))
}
function personName(people: readonly PersonOption[], id: string | null, unassigned = 'Unassigned'): string {
  return people.find((p) => p.id === id)?.full_name ?? unassigned
}
/** The pinned-header meta shows a person's FIRST name — but the unassigned marker is not a name
 *  and passes through whole ("Belum ditugaskan", never "Belum": firstName splits on the first
 *  space, which truncated the Bahasa marker to a bare "Belum"). */
function metaShortName(people: readonly PersonOption[], id: string | null, unassigned: string): string {
  const person = people.find((p) => p.id === id)
  return person ? firstName(person.full_name) : unassigned
}
function buOptions(bus: readonly BusinessUnitOption[]): RecordFieldOption[] {
  return bus.map((b) => ({ value: b.id, label: b.name }))
}
function buName(bus: readonly BusinessUnitOption[], id: string, noneMarker = '—'): string {
  return bus.find((b) => b.id === id)?.name ?? noneMarker
}

/** Wrap a field spec with the shared editable policy.
 *
 *  R4 (owner review r2): an editable-by-design field that the current viewer can't edit shows NO
 *  per-field reason — just its value, read-only, with no edit affordance. The single whole-record
 *  read-only note (why the viewer can't edit) is carried ONCE by RecordViewer's footer from
 *  adapter.permission.reason. Stamping the same "you can't edit this task" line onto every field
 *  was the repetitive noise the owner flagged: a wall of identical reasons with no per-field intent.
 *  A genuinely field-specific reason (e.g. the honest Team-migration state, teamOwnershipField)
 *  still sets its own readOnlyReason directly; this shared wrapper simply never adds a blanket one. */
function editableSpec(
  editable: boolean,
  spec: Omit<RecordFieldSpec, 'editable'>,
): RecordFieldSpec {
  return { ...spec, editable }
}

