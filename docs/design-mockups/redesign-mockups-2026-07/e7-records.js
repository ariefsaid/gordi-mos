/* Follow-up = evidence-gated settlement; Finance confirms. */
function renderFollowup(r, { mode, person }){
  const lc = ['chased','promised','partial','settled'];
  const idx = lc.indexOf(r.lifecycle);
  const settled = r.lifecycle==='settled';
  const recordCtx = {teamId:r.teamId,buId:teams[r.teamId]?.buId};
  const canChase = !!(person && (person.id===r.ownerChaseId || can(person,'followup.chase',recordCtx)));
  const canSettle = !!(person && (person.id===r.financeConfirmId || can(person,'followup.settle',recordCtx)));
  const nextAction = r.lifecycle==='chased' && canChase ? `<button class="btn btn-sm btn-primary" data-followup-action="promise|${esc(r.id)}">Record promise</button>` :
    r.lifecycle==='promised' && (canChase||canSettle) ? `<button class="btn btn-sm btn-primary" data-followup-action="partial|${esc(r.id)}">Record partial payment</button>` :
    r.lifecycle==='partial' && canSettle ? `<button class="btn btn-sm btn-primary" data-followup-action="settle|${esc(r.id)}">Attempt settlement</button>` : '';
  return `
    ${section('Outstanding', kv([['Counterparty', esc(r.counterparty)],['Amount', `<span class="tabular">${money(r.amount)}</span>`],['Balance', `<span class="tabular">${money(r.balance)}</span>`],['Age', `<span class="${r.ageDays>30?'delta down':''}">${r.ageDays} days</span>`],['Owner (chase)', personLine(r.ownerChaseId)],['Finance confirm', personLine(r.financeConfirmId)]]))}
    ${section('Settlement lifecycle', `
      <div class="lifecycle">${lc.map((s,i)=>`<div class="lc-step ${i<idx?'done':''} ${i===idx?'cur':''}"></div>`).join('')}</div>
      <div class="lc-labels">${lc.map((s,i)=>`<span class="${i===idx?'active':''}">${s}</span>`).join('')}</div>
      ${!settled?`<div class="callout warn" style="margin-top:10px;font-size:12px">Reaching <b>Settled</b> requires: ${r.settleRequires.join(', ')}. There is no settle-without-evidence path.</div>`:''}
      ${r.settlementError?`<div class="callout error" data-state="validation" style="margin-top:8px;font-size:12px"><b>Cannot settle:</b> ${esc(r.settlementError)} <button class="btn btn-sm btn-outline" data-followup-action="add-proof|${esc(r.id)}" style="margin-left:6px">Add cash date + proof</button></div>`:''}
      ${nextAction?`<div style="margin-top:10px">${nextAction}</div>`:''}
    `)}
    ${r.promises?.length?section('Promises & payments', `<div class="stack">${r.promises.map(p=>`<div class="callout" style="font-size:12px">Promise ${money(p.amount)} · cash-in ${esc(p.cashInDate)} · proof ${esc(p.proof)}</div>`).join('')}</div>`):''}
    ${section('Audit history', `<div class="stack">${(r.history||[]).map(h=>`<div class="muted-2" style="font-size:12px">${esc(h.at)} — ${esc(h.event)} (${esc(people[h.by]?.name||h.by)})</div>`).join('')}</div>`)}
  `;
}

