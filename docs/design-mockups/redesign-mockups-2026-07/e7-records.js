export function renderRecord(id, { mode = 'panel', person = null } = {}){
  const record = records[id];
  if (!record) return `<section role="alert" class="denied-state"><span class="lock-ico" data-i="search"></span><h3>Record not found</h3><p class="muted-2">No record exists for “${esc(id)}”.</p></section>`;
  const renderer = recordRenderers[record.type];
  if (!renderer) return `<section role="alert" class="denied-state"><h3>Unsupported record type</h3><p class="muted-2">This prototype cannot display “${esc(record.type)}” records yet.</p></section>`;
  const badge = typeBadge[record.type] || record.type;
  const titleInner = record.title || record.name || record.ref || record.id;
  return `<article class="e7-record e7-record--${mode}" data-record-id="${esc(id)}">
    <header class="e7-rec-head">
      <div>
        <div class="e7-rec-type">${badge}</div>
        <div class="e7-rec-title">${esc(titleInner)}</div>
      </div>
      <div class="actions">${mode==='panel'?`<a class="btn btn-sm btn-ghost" href="#/record/${esc(id)}" data-open-page="${esc(id)}">Open full page →</a>`:''}</div>
    </header>
    <div class="e7-rec-body">${renderer(record, { mode, person })}</div>
  </article>`;
}

