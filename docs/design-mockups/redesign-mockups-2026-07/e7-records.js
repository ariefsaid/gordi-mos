/* Task = Team + PIC + Supervisor + Status. Never RACI; RACI lives on Objectives, Projects, Processes. */
function renderTask(r, { mode }){
  const supervisorSrc = r.supervisorSource || 'Inherited from parent work';
  const parent = r.parentProject ? `<dt>Project (RACI)</dt><dd>${linkTo(r.parentProject)}</dd>` :
                 r.parentRun ? `<dt>Process Run</dt><dd>${linkTo(r.parentRun)}</dd>` :
                 r.sourceSignal ? `<dt>From Signal</dt><dd>${linkTo(r.sourceSignal)}</dd>` : '';
  const generated = r.generatedFrom ? `<dt>Generated by</dt><dd>${linkTo(r.generatedFrom)}</dd>` : '';
  const exception = r.sourceException ? `<dt>From Exception</dt><dd>${linkTo(r.sourceException)}</dd>` : '';
  const checklist = (r.checklist?.length) ? section('Checklist items', r.checklist.map(c =>
    `<div class="check-row"><span class="check-box ${c.done?'pass':''}">${c.done?'<span data-i="check"></span>':''}</span><div class="body"><div class="t">${esc(c.label)}</div></div></div>`).join('')) : '';
  const archived = r.archivedAt ? `<p class="callout warn" data-state="archived" style="font-size:12px">Archived ${esc(r.archivedAt)} — restorable. Hard delete is unavailable.</p>` : '';
  return `
    ${section('Ownership', kv([
      ['Team', teamLine(r.teamId)],
      ['PIC', `<span class="mention-chip">${esc(people[r.picId]?.name||'—')}</span>`],
      ['Supervisor', `<span class="mention-chip">${esc(people[r.supervisorId]?.name||'—')}</span> <span class="muted-2">· ${esc(supervisorSrc)}</span>`],
      ['Classification', r.classification||'—'],
    ]))}
    ${section('Status & timing', kv([
      ['Status', pill(r.status)],
      ['Due', r.due?esc(r.due):'—'],
      ...(parent?[['Source link', parent.replace(/<dt>[^<]*<\/dt><dd>([\s\S]*?)<\/dd>/, '$1')]]:[]),
      ...(generated?[['Generated by', generated.replace(/<dt>[^<]*<\/dt><dd>([\s\S]*?)<\/dd>/, '$1')]]:[]),
      ...(exception?[['From Exception', exception.replace(/<dt>[^<]*<\/dt><dd>([\s\S]*?)<\/dd>/, '$1')]]:[]),
      ...(r.standardId?[['Governing Standard', linkTo(r.standardId)]]:[]),
    ]))}
    ${r.description?section('Details', `<p>${esc(r.description)}</p>`):''}
    ${checklist}
    ${archived}
    ${section('Activity', `<div class="e7-rel-list"><div class="callout" style="font-size:12px">Comments and changes to this Task appear here.</div></div>`)}
  `;
}

/* Signal = factual. NO PIC/Supervisor/due/Status/resolution (A1/A2/A13). */
function renderSignal(r, { mode, person }){
  if (r.retracted){
    return section('Signal retracted', `
      <div class="rev-tomb"><span class="ico" data-i="alert"></span> This Signal was retracted by ${esc(people[r.authorId]?.name)}.
      Reason: ${esc(r.retractReason)} An audit tombstone remains; the Signal is excluded from feeds/analytics. No hard delete.</div>
      <p class="muted-2" style="font-size:12px;margin-top:8px">Wrong provenance requires retract + repost; owning Team is immutable after post.</p>`);
  }
  const mentions = (r.mentions||[]).map(m => m.kind==='team'?`@${esc(teams[m.ref]?.name||m.ref)}`:`@${esc(people[m.ref]?.name||m.ref)}`).join(' ');
  const acks = (r.acks||[]).map(id=>personChip(id)).join(' ');
  const linked = (r.linkedWork||[]).map(w=>linkTo(w.id)).join(' ');
  const revs = (r.revisions||[]).length;
  return `
    <div data-journey="J12 J13 J14" data-scenario="S3">
    ${section('Facts', kv([
      ['Author', personLine(r.authorId)],
      ['Owning Team', teamLine(r.owningTeamId)],
      ['Occurred', esc(r.occurredAt)],
      ['Attention', attentionPill(r.attention)],
      ['Category', r.category||'Uncategorised'],
    ]))}
    ${section('What happened', `<p>${esc(r.body)}</p>`)}
    ${mentions?section('Mentions & visibility', `<p class="muted" style="font-size:12px;margin-bottom:6px">Owning Team sets default visibility (upward layers); mentions grant access <b>and</b> notify. ${mentions}</p><div>${(r.mentions||[]).map(m=>`<span class="mention-chip">${m.kind==='team'?'@'+esc(teams[m.ref]?.name):'@'+esc(people[m.ref]?.name)}</span>`).join(' ')}</div>`):''}
    ${section('Linked work (many-to-many)', `<p class="muted-2" style="font-size:12px;margin-bottom:6px">A Signal is never promoted or resolved. Action becomes a linked Task.</p><div class="e7-rel-list">${linked||'<span class="muted-2">No linked Tasks yet.</span>'}</div>${person&&can(person,'task.create')?`<button class="btn btn-sm btn-outline" style="margin-top:8px" data-signal-task="${esc(r.id)}">Create linked Task</button>`:''}`)}
    ${section('Acknowledgement', `<p class="muted-2" style="font-size:12px">Acknowledged = “I have seen this.” It is not ownership, approval, or a promise to act.</p><div>${acks||'<span class="muted-2">No acknowledgements yet.</span>'}</div>`)}
    ${section('Discussion', `<div class="stack">${(r.comments||[]).map(c=>`<div class="deputy-msg bot" style="align-self:flex-start"><div><b>${esc(people[c.who]?.name)}</b>: ${esc(c.text)}</div></div>`).join('')||'<span class="muted-2">No comments.</span>'}</div>${revs?`<p class="muted-2" style="font-size:12px">${revs} revision(s) — correctable, never silently rewritten.</p>`:''}</div>`)}
    </div>
  `;
}

/* ── Typed structured document canvas (design contract D7) ───────────────
   One grammar for Process designer + Project/Standard detail pages: pinned
   required properties that cannot be removed, a `/` insert menu limited to
   contract-valid nested objects, and visible autosave pending/saved/error.
   No separate view/edit mode — capability gates the edit affordances only. */
const CANVAS_CONTRACTS = {
  process: [
    { kind:'task-def', label:'Generated Task definition', icon:'plus' },
    { kind:'checklist', label:'Checklist item', icon:'check' },
    { kind:'check', label:'Measured Check', icon:'target' },
    { kind:'field', label:'Input field', icon:'listChecks' },
    { kind:'evidence', label:'Evidence requirement', icon:'check' },
    { kind:'signoff', label:'Sign-off', icon:'flag' },
  ],
  project: [
    { kind:'task-ref', label:'Contributing Task', icon:'plus' },
    { kind:'milestone', label:'Milestone', icon:'target' },
    { kind:'field', label:'Field', icon:'listChecks' },
    { kind:'note', label:'Note', icon:'layers' },
  ],
};
const KIND_LABEL = { 'task-def':'Task definition', checklist:'Checklist item', check:'Measured Check', field:'Input field', evidence:'Evidence', signoff:'Sign-off', 'task-ref':'Task', milestone:'Milestone', note:'Note' };
const KIND_ICON = { 'task-def':'plus', checklist:'check', check:'target', field:'listChecks', evidence:'check', signoff:'flag', 'task-ref':'plus', milestone:'target', note:'layers' };

function canvasAutosave(r){
  const s = r.canvasSave || 'saved';
  const map = { saved:['done','All changes saved'], pending:['pending','Saving…', 'data-state="pending"'], error:['error','Validation error — resolve to publish', 'data-state="validation"'] };
  const [cls, txt, extra] = map[s] || map.saved;
  return `<div class="canvas-save"><span class="canvas-save-dot ${cls}"></span><span class="inline-state ${cls}" ${extra||''}>${esc(txt)}</span></div>`;
}
function canvasPinned(label, value){
  return `<div class="canvas-pinned"><span class="canvas-pin" title="Required — cannot be removed" aria-label="Required property"><span class="ico" data-i="lock"></span></span><div class="canvas-pinned-body"><div class="canvas-pinned-label">${esc(label)}</div><div class="canvas-pinned-value">${value}</div></div></div>`;
}
function canvasBlock(r, sec, canEdit){
  const k = sec.kind; const klabel = KIND_LABEL[k]||k; const ico = KIND_ICON[k]||'layers';
  const edit = (field, text) => canEdit ? `<div class="canvas-block-title" data-inline-canvas="${esc(r.id)}|${esc(sec.id)}|${field}">${esc(text)}</div>` : `<div class="canvas-block-title ro">${esc(text)}</div>`;
  let body = '';
  if (k==='task-def') body = `${edit('title', sec.title||'Untitled Task')}<div class="canvas-block-meta">owner ${esc(sec.own||'—')} · supervisor source <b>${esc(sec.sup||'Process A')}</b></div>`;
  else if (k==='check') body = `<div class="canvas-block-title ro">${esc(sec.label)}${sec.pinned?' <span class="canvas-pin-inline" title="Required Check"><span class="ico" data-i="lock"></span></span>':''}</div><div class="canvas-block-meta">Standard ${sec.spec?linkTo(sec.spec):'—'} · measured control</div>`;
  else if (k==='checklist') body = `${edit('label', sec.label||'Checklist item')}<div class="canvas-block-meta">manual checklist item</div>`;
  else if (k==='field') body = `${edit('label', sec.label||'Field')}<div class="canvas-block-meta">input type ${esc(sec.input||'text')}</div>`;
  else if (k==='evidence') body = `${edit('label', sec.label||'Evidence required')}<div class="canvas-block-meta">required evidence attachment</div>`;
  else if (k==='signoff') body = `<div class="canvas-block-title ro">${esc(sec.label||'Sign-off')}</div><div class="canvas-block-meta">by ${esc(sec.role||'Supervisor')}</div>`;
  else if (k==='task-ref') body = `<div class="canvas-block-title ro">${linkTo(sec.task, records[sec.task]?.title||'Task')}</div><div class="canvas-block-meta">contributing Task · each carries its own PIC + Supervisor</div>`;
  else if (k==='milestone') body = `${edit('label', sec.label||'Milestone')}<div class="canvas-block-meta">${sec.due?'due '+esc(sec.due):''}</div>`;
  else if (k==='note') body = `${edit('label', sec.label||'Note')}`;
  const removable = canEdit && !sec.pinned;
  return `<div class="canvas-block" data-canvas-block="${esc(r.id)}|${esc(sec.id)}"><span class="canvas-kind" data-i="${ico}"></span><div class="canvas-block-body">${body}<div class="canvas-kind-tag">${esc(klabel)}</div></div>${removable?`<button class="e7-iconbtn canvas-remove" data-canvas-remove="${esc(r.id)}|${esc(sec.id)}" aria-label="Remove ${esc(klabel)}">✕</button>`:''}</div>`;
}
function canvasInsert(recordId, contract, canEdit){
  if (!canEdit) return '';
  return `<button class="canvas-insert" data-canvas-insert="${esc(recordId)}|${esc(contract)}" aria-haspopup="menu"><span class="mono">/</span> Insert a block</button>`;
}

/* Process = BU-governed, RACI, versioned. A Person publishes.
   Renders as a typed structured document canvas (design contract D7). */
function renderProcess(r, { mode, person }){
  const raci = [['Accountable (A)', personLine(r.accountableId)],['Responsible (R)', personLine(r.responsibleId)],
    ['Consulted (C)', (r.consulted||[]).map(personLine).join(' ')||'—'],['Informed (I)', (r.informed||[]).map(personLine).join(' ')||'—']];
  const canEdit = !!(person && can(person,'process'+'.'+'draft',{buId:r.buId}));
  const secs = r.sections||[];
  const pinned = [
    canvasPinned('Purpose', esc(r.title)),
    canvasPinned('Owning BU', buLine(r.buId)),
    canvasPinned('Cadence / trigger', esc(r.cadence||'—')),
    canvasPinned('Accountable (A) / Responsible (R)', `${personLine(r.accountableId)} / ${personLine(r.responsibleId)}`),
  ];
  return `
    <div data-journey="J09" data-scenario="S2">
    <div class="canvas-toolbar">${canvasAutosave(r)}${canEdit?`<button class="btn btn-sm btn-outline" data-canvas-demo-error="${esc(r.id)}">Show a validation error</button>`:''}<span class="basis-chip">live document</span></div>
    ${section('Required properties', `<div class="canvas-pinned-grid">${pinned.join('')}</div><p class="muted-2" style="font-size:12px;margin-top:8px">Pinned by the Process definition — they cannot be removed. ${esc(people[r.accountableId]?.name)} (Process A) edits and publishes new versions.</p>`)}
    ${section('RACI', kv(raci)+`<p class="muted-2" style="font-size:12px;margin-top:6px">A Person acts for the Team; the Accountable Person publishes. RACI lives here, never on a Task.</p>`)}
    ${section('Definition sections', `<p class="muted-2" style="font-size:12px;margin-bottom:8px">Type-aware, reorderable blocks. Generated Tasks become Tasks in a Run, owned by one Team each; their default Supervisor is the Process A unless an override is shown.</p>
      <div class="canvas-blocks">${secs.map(s=>canvasBlock(r,s,canEdit)).join('')||'<div class="empty-state" data-state="empty"><h3>No sections yet</h3><p>Use the insert menu to add valid blocks.</p></div>'}</div>
      ${canvasInsert(r.id,'process',canEdit)}
      ${canEdit?'':`<p class="muted-2" style="font-size:12px;margin-top:6px">You can view this Process, but only its authorized managers can edit the draft.</p>`}`)}
    ${section('Linked Standards', `<div class="e7-rel-list">${(r.linkedStandards||[]).map(id=>`<a class="e7-relation" href="#/record/${id}" data-open-record="${id}"><span class="t">${esc(records[id]?.title)}</span><span class="s">Standard v${records[id]?.publishedVersion}</span></a>`).join('')}</div>`)}
    ${r.linkedTasks?.length?section('Generated work in active Runs', `<p class="muted-2" style="font-size:12px;margin-bottom:6px">Occurrence Tasks remain separate records with Team, PIC, and Supervisor.</p><div class="e7-rel-list">${r.linkedTasks.map(id=>linkTo(id,undefined,'e7-relation')).join('')}</div>`):''}
    ${section('Adopted by Teams', `<div>${(r.adoptedBy||[]).map(id=>`<span class="mention-chip">${esc(teams[id]?.name)}</span>`).join(' ')}</div><p class="muted-2" style="font-size:12px;margin-top:6px">Publication never changes adoption automatically — a Team's Accountable person adopts it separately, with an effective date.</p>`)}
    </div>
  `;
}

/* Run = Team-scoped occurrence; snapshot version retained. */
function renderRun(r, { mode }){
  return `
    ${section('Occurrence', kv([['Team', teamLine(r.teamId)],['Process', linkTo(r.processId)],['Snapshot', `v${r.snapshotVersion} <span class="basis-chip">snapshot retained</span>`],['Status', pill(r.status)],['Started', r.startedAt?esc(r.startedAt):'—'],...(r.shift?[['Shift',r.shift],['Area',r.area]]:[])]))}
    ${section('Snapshot note', `<p class="callout info" data-state="version" style="font-size:12px">This Run keeps <b>v${r.snapshotVersion}</b>. If the Process or a Standard publishes a new version, this Run is <b>not</b> changed; only future unmaterialized Runs adopt it.</p>`)}
    ${section('Steps & Checks', `<div class="stack">${(r.steps||[]).map(s=>renderStep(s)).join('')||'<span class="muted-2">No steps.</span>'}</div>`)}
    ${r.tasks?.length?section('Generated Tasks', `<div class="e7-rel-list">${r.tasks.map(id=>`<a class="e7-relation" href="#/record/${id}" data-open-record="${id}"><span class="t">${esc(records[id]?.title)}</span><span class="s">${pill(records[id]?.status)}</span></a>`).join('')}</div>`):''}
    ${r.signals?.length?section('Signals', `<div class="e7-rel-list">${r.signals.map(id=>linkTo(id,undefined,'e7-relation')).join('')}</div>`):''}
  `;
}
function renderStep(s){
  if (s.kind==='check'){
    const fail = s.result==='fail';
    return `<div class="check-row"><span class="check-box ${fail?'fail':'pass'}">${fail?'!':(s.done!==false?'<span data-i="check"></span>':'')}</span>
      <div class="body"><div class="t">${esc(s.label)}</div><div class="s">Submitted: <b>${esc(s.value)}</b> · Standard ${linkTo(s.spec, 'view')}</div></div>
      ${s.evidence?`<span class="evidence"><span data-i="check"></span>${esc(s.evidence)}</span>`:''}
      ${s.exceptionId?`<a class="rel-pill" href="#/record/${s.exceptionId}" data-open-record="${s.exceptionId}" style="background:var(--e7-blocked-tint);color:var(--e7-blocked-text)">Exception →</a>`:''}
    </div>`;
  }
  if (s.kind==='form'){
    return `<div class="check-row"><span class="check-box" style="background:var(--e7-surface-3)"></span><div class="body"><div class="t">${esc(s.label)}</div><div class="s">Form: ${(s.fields||[]).map(f=>`${esc(f.k)}=<b>${esc(f.v)}</b>`).join(' · ')}</div></div></div>`;
  }
  if (s.kind==='task'){
    return `<div class="check-row"><span class="check-box ${s.done?'pass':''}"></span><div class="body"><div class="t">${esc(s.label)}</div><div class="s">${linkTo(s.taskId,'Open Task')}</div></div></div>`;
  }
  // instruction / checklist
  return `<div class="check-row"><span class="check-box ${s.done?'pass':''}">${s.done?'<span data-i="check"></span>':''}</span><div class="body"><div class="t">${esc(s.label)}</div><div class="s">Instruction / checklist</div></div></div>`;
}

/* Standard = BU-canonical, versioned, no RACI. Publisher = Person + capability. */
function renderStandard(r, { mode }){
  const diff = r.upgrade?.available ? `
    <div class="diff-block">
      <div class="diff-row"><div><b>v${r.version}</b> (current)</div><div><b>v${r.upgrade.toVersion}</b> (published)</div></div>
      <div class="diff-row"><div>${esc(r.upgrade.diff.from)}</div><div>${esc(r.upgrade.diff.to)}</div></div>
    </div>
    <p class="muted-2" style="font-size:12px;margin-top:6px">The accountable person for each linked Process or Project chooses when to use this version. Active Runs stay unchanged.</p>` : '';
  return `
    ${section('Definition', kv([['Business unit', buLine(r.buId)],['Version', `v${r.publishedVersion} published`],['Published by', esc(people[r.publisherId]?.name)] ]))}
    ${section('Steps', (r.steps||[]).map(s=>{ const stepIcon = {instruction:'book',measured:'target',evidence:'check',confirmation:'check',form:'listChecks'}[s.kind]||'layers'; return `<div class="check-row" style="cursor:default"><span class="check-box" style="background:var(--e7-surface-3)"><span class="ico" data-i="${stepIcon}"></span></span><div class="body"><div class="t">${esc(s.kind)}</div><div class="s">${esc(s.text)}</div></div></div>`; }).join(''))}
    ${section('Consumed by', `<div class="e7-rel-list">${(r.consumedBy||[]).map(id=>linkTo(id,undefined,'e7-relation')).join('')}</div>`)}
    ${diff?section('Upgrade available', `<div data-scenario="S4">${diff}</div>`):''}
  `;
}

