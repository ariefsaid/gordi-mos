/* ── shared HTML helpers ──────────────────────────────────────────────────── */
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const money = (n) => 'Rp ' + Number(n ?? 0).toLocaleString('id-ID');
export function linkTo(id, label, cls = 'rel-pill') {
  const r = records[id]; if (!r) return esc(label);
  const l = label || r.title || r.id;
  return `<a class="${cls}" href="#/record/${id}" data-open-record="${id}">${esc(l)}</a>`;
}
const personChip = (id) => {
  const p = people[id]; if (!p) return '—';
  return `<span class="mention-chip">${esc(p.name)}</span>`;
};
const personLine = (id, role) => {
  const p = people[id]; if (!p) return '—';
  return `${esc(p.name)} <span class="muted-2">· ${esc(p.role)}</span>`;
};
const teamLine = (id) => { const t = teams[id]; return t ? `${esc(t.name)}` : '—'; };
const buLine = (id) => { const b = bus[id]; return b ? esc(b.name) : '—'; };

function pill(status){
  const map = { 'Open':'open','In Progress':'progress','Done':'done','Blocked':'blocked','Published':'done','Draft':'warn','Completed':'done' };
  const cls = map[status] || 'neutral';
  return `<span class="pill ${cls}"><span class="dot"></span>${esc(status)}</span>`;
}
function attentionPill(a){
  const cls = a==='Urgent'?'blocked':(a==='Needs attention'?'warn':'neutral');
  return `<span class="pill ${cls}"><span class="dot"></span>${esc(a)}</span>`;
}
function kv(rows){
  return `<dl class="kv">${rows.map(([k,v])=>`<dt>${esc(k)}</dt><dd>${v??'—'}</dd>`).join('')}</dl>`;
}
function section(title, inner, icon){
  return `<div class="e7-rec-section"><h4>${icon?`<span class="ico" data-i="${icon}"></span> `:''}${esc(title)}</h4>${inner}</div>`;
}

